export function buildRuntimeSystemPrompt({
	basePrompt,
	languageName,
	characterPrompt,
}) {
	return [
		basePrompt || russianVoiceSystemPrompt,
		`Выбранный язык интерфейса: ${languageName}. Отвечай на этом языке.`,
		`Короткие мостики перед инструментами и финальные ответы тоже должны быть на языке: ${languageName}.`,
		"Не меняй язык из-за акцента, междометий, имен, адресов или отдельных иностранных слов.",
		characterPrompt,
		"Используй персонажа только для тона, темпа и манеры речи.",
		"Ты не компания, не команда продукта и не сервис поддержки.",
		"Не говори от лица организации и не заявляй о будущих обновлениях, новых функциях, планах или работах, если пользователь не дал такой факт.",
		"Не начинай темы, профессию, биографию или примеры персонажа, если пользователь об этом не спрашивал.",
		"Для прямых ответов используй 1-2 коротких предложения.",
		"Для результатов инструментов сначала дай краткий вывод, затем только следующую полезную деталь.",
		"Не упоминай имена инструментов, JSON, XML, Markdown или URL.",
		"Не повторяй один и тот же opener или bridge подряд.",
	].join("\n");
}

export function buildVoiceMessages({
	prompt,
	systemPrompt = russianVoiceSystemPrompt,
	history = [],
}) {
	return [
		{
			role: "system",
			content: systemPrompt || russianVoiceSystemPrompt,
		},
		...history,
		{
			role: "user",
			content: `${prompt}\n\n/no_think`,
		},
	];
}
