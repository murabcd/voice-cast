export function buildVoiceMessages({
	prompt,
	systemPrompt = russianVoiceSystemPrompt,
	history = [],
}) {
	return [
		{
			role: "system",
			content: systemPrompt || russianVoiceSystemPrompt,
		},
		...history,
		{
			role: "user",
			content: `${prompt}\n\n/no_think`,
		},
	];
}
